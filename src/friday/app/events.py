"""États de l'assistant et contrat entre l'assistant et les interfaces."""

from enum import Enum
from typing import Protocol

import numpy as np

from friday.tools.base import Display


class AssistantState(Enum):
    LOADING = "Initialisation…"
    IDLE = "En veille"
    LISTENING = "À l'écoute"
    THINKING = "Réflexion…"
    SPEAKING = "Parle"
    PAUSED = "Mode jeu"  # carte graphique rendue au jeu (G1)


class AssistantListener(Protocol):
    """Ce qu'une interface (terminal, fenêtre…) reçoit de l'assistant.

    Attention : ces méthodes sont appelées depuis des threads de travail, pas depuis
    le thread de l'interface.
    """

    def on_ready(self, info: str) -> None: ...
    def on_state(self, state: AssistantState) -> None: ...
    def on_user_message(self, text: str, by_voice: bool) -> None: ...
    def on_reply_start(self) -> None: ...
    def on_reply_chunk(self, text: str) -> None: ...
    def on_reply_end(self, interrupted: bool) -> None: ...
    def on_notice(self, text: str) -> None: ...
    def on_tool(self, label: str) -> None: ...
    def on_tool_done(self, ok: bool) -> None: ...
    def on_display(self, display: Display) -> None: ...
    def on_memory(self, text: str) -> None: ...
    def on_confirmation(self, question: str, seconds: float = 60.0) -> None: ...
    def on_mic_level(self, level: float) -> None: ...
    def on_speech_audio(self, audio: np.ndarray, sample_rate: int) -> None: ...


class NullListener:
    """Implémentation vide : chaque interface ne surcharge que ce qui l'intéresse."""

    def on_ready(self, info: str) -> None: ...
    def on_state(self, state: AssistantState) -> None: ...
    def on_user_message(self, text: str, by_voice: bool) -> None: ...
    def on_reply_start(self) -> None: ...
    def on_reply_chunk(self, text: str) -> None: ...
    def on_reply_end(self, interrupted: bool) -> None: ...
    def on_notice(self, text: str) -> None: ...
    def on_tool(self, label: str) -> None: ...
    def on_tool_done(self, ok: bool) -> None: ...
    def on_display(self, display: Display) -> None: ...
    def on_memory(self, text: str) -> None: ...
    def on_confirmation(self, question: str, seconds: float = 60.0) -> None: ...
    def on_mic_level(self, level: float) -> None: ...
    def on_speech_audio(self, audio: np.ndarray, sample_rate: int) -> None: ...
